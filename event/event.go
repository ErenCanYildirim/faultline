// Package event defines the wire contract shared by the SDK, the ingest API
// and the worker. The SDK fills an Event, the ingest API validates it and
// stamps server-side fields, and the worker reads it from the queue.
//
// The wire format is JSON (see docs/event-contract.md). Field names are
// snake_case and stable: renaming one is a breaking change for every SDK.
package event

import "time"

// Level is the severity of an event.
type Level string

const (
	LevelDebug   Level = "debug"
	LevelInfo    Level = "info"
	LevelWarning Level = "warning"
	LevelError   Level = "error"
	LevelFatal   Level = "fatal"
)

// Valid reports whether l is one of the known levels.
func (l Level) Valid() bool {
	switch l {
	case LevelDebug, LevelInfo, LevelWarning, LevelError, LevelFatal:
		return true
	}
	return false
}

// Batch is the body of one ingest request: several events sent together.
type Batch struct {
	Events []Event `json:"events"`
}

// Event is one captured error or message.
//
// Ownership of fields:
//   - Set by the SDK: everything except ProjectID and ReceivedAt.
//   - Set by ingest: ProjectID (from the authenticated project key) and
//     ReceivedAt (server clock). Values sent by a client for these two
//     fields are ignored and overwritten, so a client can never write
//     into another project.
type Event struct {
	// EventID is a UUIDv7 string generated by the SDK. The same ID is reused
	// on every retry, which is what makes deduplication in ClickHouse work.
	EventID string `json:"event_id"`

	// ProjectID is set by ingest, never trusted from the client.
	ProjectID string `json:"project_id,omitzero"`

	// Timestamp is when the event happened, by the client's clock (UTC).
	Timestamp time.Time `json:"timestamp"`

	// ReceivedAt is when ingest accepted the event, by the server's clock.
	// Comparing it with Timestamp shows client clock skew and SDK buffering delay.
	ReceivedAt time.Time `json:"received_at,omitzero"`

	Level   Level  `json:"level"`
	Message string `json:"message,omitzero"`

	// Exception is nil for plain messages.
	Exception *Exception `json:"exception,omitzero"`

	Tags map[string]string `json:"tags,omitzero"`
	User *User             `json:"user,omitzero"`

	Release     string `json:"release,omitzero"`
	Environment string `json:"environment,omitzero"`

	// Fingerprint overrides how the event is grouped into an issue. Events
	// with the same parts group together. The part "{{default}}" stands for
	// the default grouping, so ["{{default}}", tenant] splits each issue per
	// tenant. Empty means default grouping. Note: this is the client's
	// input; the computed hash stored with the event is a different thing.
	Fingerprint []string `json:"fingerprint,omitzero"`

	SDK SDKInfo `json:"sdk"`
}

// Exception describes an error and where it happened.
type Exception struct {
	// Type is the Go type of the error, for example "*fs.PathError".
	Type string `json:"type"`
	// Value is the error text, err.Error().
	Value string `json:"value"`
	// Frames are ordered innermost first: Frames[0] is where the error was
	// captured, the last frame is the outermost caller (usually main or a
	// goroutine entry). This matches how Go prints stacks.
	Frames []Frame `json:"frames,omitzero"`
}

// Frame is one entry of a stack trace.
type Frame struct {
	// Module is the Go package path, for example "github.com/acme/shop/cart".
	Module string `json:"module"`
	// Function is the function or method name without the package path,
	// for example "(*Cart).Checkout".
	Function string `json:"function"`
	File     string `json:"file,omitzero"`
	Line     int    `json:"line,omitzero"`
	// InApp is true for the application's own code and false for the
	// standard library and third-party modules. Grouping uses in-app frames.
	InApp bool `json:"in_app"`
}

// User identifies who was affected. Every field here is personal data and is
// a target for the PII scrubbing added in Phase 2.
type User struct {
	ID        string `json:"id,omitzero"`
	Username  string `json:"username,omitzero"`
	Email     string `json:"email,omitzero"`
	IPAddress string `json:"ip_address,omitzero"`
}

// SDKInfo names the client library that produced the event.
type SDKInfo struct {
	Name    string `json:"name"`
	Version string `json:"version"`
}
