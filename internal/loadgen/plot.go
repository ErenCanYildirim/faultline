package loadgen

import (
	"fmt"
	"html"
	"io"
	"math"
	"strings"
)

// Charts for failure tests and benchmarks: one HTML file with an SVG panel
// per metric, every run as a line, and markers where a fault was injected.
// Plain SVG and no JavaScript, so the file opens anywhere and renders the
// same on GitHub Pages or in a browser from disk.

// PlotRun is one result file on the chart.
type PlotRun struct {
	Name string
	// Offset shifts the run on the time axis: a run started 15s after the
	// first one has Offset 15, so both share one clock.
	Offset float64
	Report *Report
}

// PlotMark is a vertical line at a moment, such as "worker killed".
type PlotMark struct {
	At    float64
	Label string
}

// Metric is one panel.
type Metric struct {
	Key, Title, Unit string
	value            func(cur, prev Sample) (float64, bool)
}

// Metrics are the panels the chart tool can draw.
var Metrics = map[string]Metric{
	"lag": {"lag", "Consumer lag", "events", func(c, _ Sample) (float64, bool) {
		return float64(c.Lag), c.Lag >= 0
	}},
	"acked": {"acked", "Acknowledged by ingest", "events/s", func(c, _ Sample) (float64, bool) {
		return c.Acked, true
	}},
	"generated": {"generated", "Generated by the apps", "events/s", func(c, _ Sample) (float64, bool) {
		return c.Generated, true
	}},
	"p50": {"p50", "Ingest latency p50", "ms", func(c, _ Sample) (float64, bool) {
		return c.P50Ms, c.Requests > 0
	}},
	"p99": {"p99", "Ingest latency p99", "ms", func(c, _ Sample) (float64, bool) {
		return c.P99Ms, c.Requests > 0
	}},
	"429": {"429", "Rate-limited responses (429)", "per s", func(c, p Sample) (float64, bool) {
		dt := c.T - p.T
		if dt <= 0 || c.Status429 < p.Status429 {
			return 0, false
		}
		return float64(c.Status429-p.Status429) / dt, true
	}},
	"stored": {"stored", "Stored after the run", "events", func(c, _ Sample) (float64, bool) {
		return float64(c.Stored), c.Stored > 0
	}},
}

// Colors from a palette that stays distinguishable for common color
// vision deficiencies; runs beyond four reuse it.
var plotColors = []string{"#2563eb", "#ea580c", "#16a34a", "#9333ea"}

// WritePlot writes the HTML page.
func WritePlot(w io.Writer, title string, runs []PlotRun, metrics []string, marks []PlotMark) error {
	var b strings.Builder
	fmt.Fprintf(&b, `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>%s</title>
<style>
:root { --bg:#ffffff; --fg:#111827; --muted:#6b7280; --grid:#e5e7eb; --mark:#dc2626; }
@media (prefers-color-scheme: dark) { :root { --bg:#0f172a; --fg:#e5e7eb; --muted:#94a3b8; --grid:#1e293b; --mark:#f87171; } }
body { background:var(--bg); color:var(--fg); font:14px/1.4 system-ui, sans-serif; margin:0 auto; padding:16px; max-width:960px; }
h1 { font-size:20px; margin:0 0 4px; } .sub { color:var(--muted); margin:0 0 16px; }
.legend span { display:inline-block; margin-right:16px; } .legend i { display:inline-block; width:14px; height:3px; vertical-align:middle; margin-right:6px; }
svg { width:100%%; height:auto; display:block; margin:8px 0 20px; }
svg text { fill:var(--muted); font-size:11px; } svg .title { fill:var(--fg); font-size:13px; font-weight:600; }
svg .grid { stroke:var(--grid); } svg .mark { stroke:var(--mark); stroke-dasharray:4 3; } svg .marktext { fill:var(--mark); }
</style></head><body>
<h1>%s</h1>
`, html.EscapeString(title), html.EscapeString(title))

	var ids []string
	for _, r := range runs {
		ids = append(ids, r.Report.RunID)
	}
	fmt.Fprintf(&b, "<p class=\"sub\">%s</p>\n<div class=\"legend\">", html.EscapeString(strings.Join(ids, ", ")))
	for i, r := range runs {
		fmt.Fprintf(&b, `<span><i style="background:%s"></i>%s</span>`, plotColors[i%len(plotColors)], html.EscapeString(r.Name))
	}
	b.WriteString("</div>\n")

	for _, key := range metrics {
		m, ok := Metrics[key]
		if !ok {
			return fmt.Errorf("unknown metric %q", key)
		}
		writePanel(&b, m, runs, marks)
	}
	b.WriteString("</body></html>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

type point struct{ x, y float64 }

func writePanel(b *strings.Builder, m Metric, runs []PlotRun, marks []PlotMark) {
	const width, height = 900.0, 240.0
	const left, right, top, bottom = 64.0, 16.0, 28.0, 32.0

	// Each run is a list of segments; a missing value breaks the line.
	series := make([][][]point, len(runs))
	maxX, maxY := 0.0, 0.0
	for i, r := range runs {
		var seg []point
		var prev Sample
		for j, s := range r.Report.Timeline {
			v, ok := m.value(s, prev)
			if j == 0 && m.Key == "429" {
				v, ok = 0, false
			}
			prev = s
			if !ok || math.IsNaN(v) {
				if len(seg) > 0 {
					series[i] = append(series[i], seg)
					seg = nil
				}
				continue
			}
			p := point{s.T + r.Offset, v}
			seg = append(seg, p)
			maxX, maxY = math.Max(maxX, p.x), math.Max(maxY, p.y)
		}
		if len(seg) > 0 {
			series[i] = append(series[i], seg)
		}
	}
	for _, mk := range marks {
		maxX = math.Max(maxX, mk.At)
	}
	maxX, stepX := niceAxis(maxX, 6)
	maxY, stepY := niceAxis(maxY, 4)
	px := func(x float64) float64 { return left + x/maxX*(width-left-right) }
	py := func(y float64) float64 { return height - bottom - y/maxY*(height-top-bottom) }

	fmt.Fprintf(b, `<svg viewBox="0 0 %.0f %.0f" role="img" aria-label="%s">`, width, height, html.EscapeString(m.Title))
	fmt.Fprintf(b, `<text class="title" x="%.0f" y="16">%s (%s)</text>`, left, html.EscapeString(m.Title), html.EscapeString(m.Unit))
	for y := 0.0; y <= maxY+stepY/2; y += stepY {
		fmt.Fprintf(b, `<line class="grid" x1="%.1f" x2="%.1f" y1="%.1f" y2="%.1f"/>`, left, width-right, py(y), py(y))
		fmt.Fprintf(b, `<text x="%.1f" y="%.1f" text-anchor="end">%s</text>`, left-6, py(y)+4, fmtTick(y))
	}
	for x := 0.0; x <= maxX+stepX/2; x += stepX {
		fmt.Fprintf(b, `<text x="%.1f" y="%.1f" text-anchor="middle">%ss</text>`, px(x), height-bottom+16, fmtTick(x))
	}
	for _, mk := range marks {
		fmt.Fprintf(b, `<line class="mark" x1="%.1f" x2="%.1f" y1="%.1f" y2="%.1f"/>`, px(mk.At), px(mk.At), top, height-bottom)
		fmt.Fprintf(b, `<text class="marktext" x="%.1f" y="%.1f">%s</text>`, px(mk.At)+4, top+10, html.EscapeString(mk.Label))
	}
	for i, segs := range series {
		color := plotColors[i%len(plotColors)]
		for _, seg := range segs {
			var pts []string
			for _, p := range seg {
				pts = append(pts, fmt.Sprintf("%.1f,%.1f", px(p.x), py(p.y)))
			}
			fmt.Fprintf(b, `<polyline fill="none" stroke="%s" stroke-width="2" points="%s"/>`, color, strings.Join(pts, " "))
		}
	}
	b.WriteString("</svg>\n")
}

// niceAxis picks a round tick step (1, 2 or 5 times a power of ten) giving
// about n ticks, and the axis end as the first tick at or above max.
func niceAxis(max float64, n int) (end, step float64) {
	if max <= 0 {
		return 1, 1.0 / float64(n)
	}
	// The smallest round step that needs at most n+2 ticks.
	p := math.Pow(10, math.Floor(math.Log10(max/float64(n))))
	for _, f := range []float64{1, 2, 5, 10, 20} {
		step = f * p
		if math.Ceil(max/step) <= float64(n+2) {
			break
		}
	}
	return math.Ceil(max/step) * step, step
}

// niceCeil rounds up to 1, 2 or 5 times a power of ten.
func niceCeil(v float64) float64 {
	if v <= 0 {
		return 0
	}
	p := math.Pow(10, math.Floor(math.Log10(v)))
	for _, f := range []float64{1, 2, 5, 10} {
		if v <= f*p {
			return f * p
		}
	}
	return 10 * p
}

func fmtTick(v float64) string {
	switch {
	case v >= 1e6:
		return strings.TrimSuffix(strings.TrimRight(fmt.Sprintf("%.2f", v/1e6), "0"), ".") + "M"
	case v >= 1e3:
		return strings.TrimSuffix(strings.TrimRight(fmt.Sprintf("%.2f", v/1e3), "0"), ".") + "k"
	case v == math.Trunc(v):
		return fmt.Sprintf("%.0f", v)
	default:
		return fmt.Sprintf("%.1f", v)
	}
}
